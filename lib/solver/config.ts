// Хардкод-конфіг solver-а на Етапі 1: робоче вікно, буфер, дефолтні тривалості, правила.
// На Етапі 2 тривалості й правила частково замінить персональна памʼять — поки константи.

export const WORK_START = "07:00";
export const WORK_END = "22:00";
export const BUFFER_MIN = 10; // буфер між справами
export const DEFAULT_DURATION_MIN = 30; // fallback для незнайомої справи

// Гнучкі справи не ставимо в останню годину перед сном — захищений час на хаос/відпочинок.
// Фіксовані справи (явний fixed_time) це не обмежує — то свідомий вибір мами.
export const FLEXIBLE_END = "21:00";

// --- Час: "HH:MM" ↔ хвилини від опівночі ---
export function toMin(hhmm: string): number {
  const [h, m] = hhmm.split(":").map(Number);
  return h * 60 + m;
}

export function toHHMM(min: number): string {
  const h = Math.floor(min / 60);
  const m = min % 60;
  return `${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}`;
}

// --- Дефолтні тривалості: перший збіг виграє, інакше DEFAULT_DURATION_MIN ---
const DURATION_RULES: [RegExp, number][] = [
  [/зарядк|разминк/i, 20],
  [/тренуванн|трениров|спорт|\bзал\b|йог[аи]|пробіжк|пробежк/i, 60],
  [/зйомк|знімат|зняти відео|відеомонтаж|монтаж/i, 90],
  [/сніданок|завтрак/i, 20],
  [/обід|обед/i, 30],
  [/вечер[яю]|ужин/i, 40],
  [/готуват|приготуват|приготовить|готовк|варит/i, 40],
  [/прибиран|прибрат|убор|помити|помыть|пропилосос/i, 45],
  [/прогулянк|погулять|прогулк|вигуляти|вулиц|парк/i, 45],
  [/лікар|врач|поліклін|стоматолог|аналіз|аналог/i, 60],
  [/садок|садик|школ|відвест|отвез|забрат|забрать|заберу/i, 20],
  [/магазин|закуп|продукт|купит|замовит|заказ/i, 30],
  [/подзвонит|зателефон|позвонит|дзвінок|звонок|созвон/i, 15],
  [/робот|работ|зустріч|встреч|мітинг|meeting|нарад/i, 60],
  [/урок|домашк|занят|навчан|вивчит/i, 40],
];

export function durationFor(title: string): number {
  for (const [re, min] of DURATION_RULES) if (re.test(title)) return min;
  return DEFAULT_DURATION_MIN;
}

// --- Додатковий буфер збори+дорога навколо справ, що вимагають виходу з дому ---
// Тривалість справи — це сама подія; буфер — окремо, щоб сусідня справа не лізла впритул.
const TRAVEL_BUFFER_RULES: [RegExp, number][] = [
  [/лікар|врач|поліклін|стоматолог|аналіз|аналог/i, 20],
  [/садок|садик|школ|відвест|отвез|завезти|забрат|забрать|заберу/i, 15],
];

export function travelBufferFor(title: string): number {
  for (const [re, min] of TRAVEL_BUFFER_RULES) if (re.test(title)) return min;
  return 0;
}

// --- Хардкод-правила Етапу 1: вікно дозволеного часу для гнучкої справи ---
// null → без обмежень (усе робоче вікно).
// Без цих вікон solver ліпить усе в перше вільне вікно вранці — тому вечеря чи
// шкільний пікап могли опинитись о 09:00. Ритм дня — теж детермінований хардкод,
// не оцінка LLM.
const CHILD_CONTEXT = /сад|школ|дит|діт|син|доньк|дочк|ребен|ребён/i;
const isChildPickup = (title: string) => /забрат|забрать|заберу/i.test(title) && CHILD_CONTEXT.test(title);

const RULE_WINDOWS: [(title: string) => boolean, string, string][] = [
  [(t) => /зарядк|разминк|тренуванн|трениров|пробіжк|пробежк|йог[аи]/i.test(t), WORK_START, "12:00"], // зранку
  [(t) => /зйомк|знімат|зняти відео|відеомонтаж|монтаж/i.test(t), "17:00", WORK_END], // після 17:00
  [(t) => /сніданок|завтрак/i.test(t), WORK_START, "10:00"], // сніданок зранку
  [(t) => /обід|обед/i.test(t), "12:00", "15:00"], // обід ополудні
  [(t) => /вечер[яю]|ужин/i.test(t), "18:00", WORK_END], // вечеря ввечері
  [(t) => /відвест|завезти|отвез/i.test(t), WORK_START, "09:30"], // відвезти в садок/школу — зранку
  [isChildPickup, "13:00", WORK_END], // забрати дитину з садка/школи — вдень/ввечері (не "забрати посилку")
  // Явний маркер у назві ("перед сном", "на ніч") — довіряємо тексту, не вгадуємо активність.
  [(t) => /перед сном|на ніч\b|на ночь\b/i.test(t), "18:00", WORK_END],
];

export function ruleWindow(title: string): [number, number] | null {
  for (const [test, lo, hi] of RULE_WINDOWS) if (test(title)) return [toMin(lo), toMin(hi)];
  return null;
}
